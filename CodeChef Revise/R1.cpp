#include <iostream>
using namespace std;

int main(){
// 1. Syntax for printing a number in C++

cout << 12;

// This line of code will print the value “12” on the screen. 

// cout  : Pronounced as see-out, cout stands for "character output stream". It is used to output data to screen.
// <<  : This is the stream insertion operator. It is used with cout to send data to the output stream.
// 12  : This is the data we want to print. Here, it's the number 12.
// Semicolon is used to end a statement, like period (.) in English.
// 2. Syntax for printing text in C++

// To print a text, you need to enclose the text you want to output inside double quotes "..." like this

cout << "I love C++";

// This will print I love C++ to the screen. Notice how I love C++ is written inside "" (double quotes). You always have to enclose your text in double quotes ("") when printing.

// 3. Syntax for generating output of a mathematical expression in C++

cout << 21 + 40;

// What do you think will this line of code print? You are right if you think it will print 61.
}